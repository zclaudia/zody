// session 编译参数：被测源码集合与链接顺序必须保持固定。
import { join } from "node:path";
import {
  FIXED_ARCH,
  FIXED_DEPLOYMENT_TARGET,
  R10_COMPILE_SOURCES,
  R11_COMPILE_SOURCES,
  SESSION_SOURCES,
} from "./cua-desktop-session-config.mjs";

export function sessionCompileArgs(
  toolchain,
  { srcDir, r10SrcDir, includeRoot, visualRoot, output },
) {
  const sdk = toolchain.sdk.path;
  const sources = [
    ...SESSION_SOURCES.map((name) => join(srcDir, name)),
    ...R11_COMPILE_SOURCES.map((name) => join(srcDir, name)),
    ...R10_COMPILE_SOURCES.map((name) => join(r10SrcDir, name)),
  ];
  return [
    "-std=c++17",
    "-x",
    "objective-c++",
    "-fobjc-arc",
    "-arch",
    FIXED_ARCH,
    "-isysroot",
    sdk,
    `-mmacosx-version-min=${FIXED_DEPLOYMENT_TARGET}`,
    "-O2",
    "-Wall",
    "-Wextra",
    "-Werror",
    "-DCUA_R11_HAVE_VISUAL",
    "-I",
    srcDir,
    "-I",
    r10SrcDir,
    "-I",
    includeRoot,
    "-I",
    join(visualRoot, "lib"),
    ...sources,
    "-x",
    "none",
    join(visualRoot, "lib/libcua_macos_visual_round11.a"),
    "-L",
    join(sdk, "usr/lib/swift"),
    "-Wl,-rpath,/usr/lib/swift",
    "-liconv",
    "-lbsm",
    "-framework",
    "Foundation",
    "-framework",
    "Security",
    "-framework",
    "CoreFoundation",
    "-framework",
    "CoreGraphics",
    "-framework",
    "IOKit",
    "-framework",
    "ScreenCaptureKit",
    "-framework",
    "AppKit",
    "-framework",
    "ApplicationServices",
    "-o",
    output,
  ];
}

